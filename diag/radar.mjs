import { chromium, devices } from "playwright";
const url = process.argv[2] || "http://localhost:8080/index.html";
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices["iPhone 13"], geolocation: { latitude: 33.9519, longitude: -83.3576 }, permissions: ["geolocation"] });
const page = await ctx.newPage();
const log = [];
page.on("console", (m) => log.push(`console.${m.type()}: ${m.text()}`));
page.on("pageerror", (e) => log.push(`pageerror: ${e.message}`));
const reqs = {};
page.on("response", (r) => { const u = r.url(); if (/rainviewer|openstreetmap|leaflet/.test(u)) { const k = u.replace(/\/\d+\/\d+\/\d+\//, "/{z}/{x}/{y}/").replace(/\/v2\/radar\/\d+/, "/v2/radar/T"); reqs[k + " -> " + r.status()] = (reqs[k + " -> " + r.status()] || 0) + 1; } });
page.on("requestfailed", (r) => log.push(`requestfailed: ${r.url()} ${r.failure()?.errorText}`));
await page.goto(url, { waitUntil: "networkidle" });
await page.waitForTimeout(4000);
await page.screenshot({ path: "out/today.png", fullPage: true });
console.log("miniTime:", await page.textContent("#miniTime"));
await page.click("#tab-radar");
await page.waitForTimeout(5000);
console.log("frameTime:", await page.textContent("#frameTime"));
await page.screenshot({ path: "out/radar.png" });
const info = await page.evaluate(() => ({ zoom: map && map.getZoom(), center: map && map.getCenter(), frames: radarFrames.length, host: radarHost, paths: radarFrames.map(f => f.path + "@" + new Date(f.time*1000).toISOString()), radarImgs: [...document.querySelectorAll("#map img.leaflet-tile")].filter(i => i.src.includes("rainviewer")).map(i => [i.src, i.complete, i.naturalWidth, getComputedStyle(i.parentElement.parentElement).opacity]) }));
console.log(JSON.stringify(info, null, 1));
await page.click("#playBtn"); await page.waitForTimeout(6000);
console.log("after play frameTime:", await page.textContent("#frameTime"));
await page.screenshot({ path: "out/radar-play.png" });
console.log("--- requests"); for (const [k, v] of Object.entries(reqs)) console.log(v, k);
console.log("--- log"); log.forEach((l) => console.log(l));
await browser.close();
